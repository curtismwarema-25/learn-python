"""Models for the chat app."""

from datetime import timedelta
from uuid import uuid4

from django.db import models
from django.contrib.auth import get_user_model
from django.utils import timezone


User = get_user_model()
CHAT_INVITE_LIFETIME = timedelta(days=7)


def deserialize_user(user):
    """Deserialize user instance to JSON."""
    return {'username': user.username}


class TrackableDateModel(models.Model):
    """Abstract model to Track the creation/updated date for a model."""

    create_date = models.DateTimeField(auto_now_add=True)
    update_date = models.DateTimeField(auto_now=True)

    class Meta:
        abstract = True


def _generate_unique_uri():
    """Generates a unique uri for the chat session."""
    return str(uuid4()).replace('-', '')[:15]


def _generate_invite_token():
    """Generate an independent, URL-safe invite token."""
    return uuid4().hex


class ChatSession(TrackableDateModel):
    """ A Chat Session. The uri's are generated by taking the first 15 characters from a UUID """

    owner = models.ForeignKey(User, on_delete=models.PROTECT)
    uri = models.URLField(default=_generate_unique_uri, unique=True)
    invite_token = models.CharField(
        max_length=32, null=True, blank=True, unique=True
    )
    invite_expires_at = models.DateTimeField(null=True, blank=True)

    def rotate_invite(self):
        """Create a fresh seven-day invite, invalidating any prior link."""
        self.invite_token = _generate_invite_token()
        self.invite_expires_at = timezone.now() + CHAT_INVITE_LIFETIME
        self.save(
            update_fields=('invite_token', 'invite_expires_at', 'update_date')
        )

    def revoke_invite(self):
        """Invalidate the current invite link."""
        self.invite_token = None
        self.invite_expires_at = None
        self.save(
            update_fields=('invite_token', 'invite_expires_at', 'update_date')
        )


class ChatSessionMessage(TrackableDateModel):
    """Store messages for a session."""

    user = models.ForeignKey(User, on_delete=models.PROTECT)
    chat_session = models.ForeignKey(
        ChatSession, related_name='messages', on_delete=models.PROTECT
    )
    message = models.TextField(max_length=2000)

    def to_json(self):
        """deserialize message to JSON."""
        return {
            'id': self.id,
            'user': deserialize_user(self.user),
            'message': self.message
        }


class ChatSessionMember(TrackableDateModel):
    """Store all users in a chat session."""

    chat_session = models.ForeignKey(
        ChatSession, related_name='members', on_delete=models.PROTECT
    )
    user = models.ForeignKey(User, on_delete=models.PROTECT)

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=('chat_session', 'user'),
                name='uniq_chat_session_member_user'
            )
        ]
